import type { Metadata } from "next";
import { Onest } from "next/font/google";
import "./globals.css";
import Nav from "@/components/ui/Nav";
import Footer from "@/components/sections/Footer";
import { brand } from "@/lib/content";
import { SITE_URL } from "@/lib/site";

// Onest carries display and body. One variable family instead of three
// static ones: fewer requests, and it is the same typeface the reference
// site uses, free under the OFL via Google Fonts.
const onest = Onest({
  variable: "--font-onest",
  subsets: ["latin"],
  weight: ["400", "500", "600", "700", "800"],
  display: "swap",
});

// Section 5. The OG image is generated by app/opengraph-image.tsx and picked
// up automatically, so no manual `images` entry is needed here.
export const metadata: Metadata = {
  metadataBase: new URL(SITE_URL),
  title:
    "Calcify International — Enterprise Digital Infrastructure & AI Solutions",
  description:
    "Calcify International builds ERP, AI, cloud, and cybersecurity solutions for the world's most ambitious enterprises. 500+ projects delivered across 50+ countries.",
  openGraph: {
    url: SITE_URL,
    title:
      "Calcify International — Engineering Tomorrow's Digital Infrastructure",
    description:
      "Enterprise ERP, AI, cloud, and cybersecurity solutions, delivered at global scale.",
    siteName: "Calcify International",
    type: "website",
    locale: "en_US",
  },
  twitter: {
    card: "summary_large_image",
    title: "Calcify International",
    description:
      "Enterprise ERP, AI, cloud, and cybersecurity solutions, delivered at global scale.",
  },
  robots: { index: true, follow: true },
};

export default function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  return (
    // data-scroll-behavior: Next.js 16 no longer overrides `scroll-behavior`
    // during navigation. globals.css sets `smooth`, so without this, route
    // changes would smooth-scroll instead of jumping. See Next 16 upgrade guide.
    <html
      lang="en"
      data-scroll-behavior="smooth"
      className={`${onest.variable} h-full`}
    >
      <body className="min-h-full flex flex-col bg-void text-ink font-sans">
        {/*
          Organization structured data. `legalName` and `sameAs` are
          intentionally left out until the registered company name and
          official social profiles are confirmed — see Section 10. Publishing
          guessed values here would put wrong data into search results.
        */}
        <script
          type="application/ld+json"
          dangerouslySetInnerHTML={{
            __html: JSON.stringify({
              "@context": "https://schema.org",
              "@type": "Organization",
              name: brand.name,
              url: SITE_URL,
              logo: `${SITE_URL}/logo.svg`,
              email: brand.email,
              telephone: brand.phone,
              foundingDate: "2015",
              description:
                "Calcify International builds ERP, AI, cloud, and cybersecurity solutions for enterprise clients.",
            }),
          }}
        />
        <a href="#main" className="skip-link">
          Skip to content
        </a>
        {/*
          Static atmosphere: a fine grid and a low red wash. CSS only — no
          WebGL, no canvas, nothing to initialise before first paint.
        */}
        <div
          aria-hidden="true"
          className="pointer-events-none fixed inset-0 z-0 bg-atmosphere"
        />
        <Nav />
        <main id="main" className="relative z-10 flex-1">
          {children}
        </main>
        <div className="relative z-10">
          <Footer />
        </div>
      </body>
    </html>
  );
}
